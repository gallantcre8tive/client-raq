def _rows(tuples):
    out = []
    for name, category, unit, flow, method, price, min_qty, desc in tuples:
        out.append({
            "name": name,
            "category": category,
            "unit": unit,
            "flow_type": flow,
            "pricing_method": method,
            "base_price": float(price or 0),
            "min_qty": int(min_qty or 1),
            "description": desc,
        })
    return out


